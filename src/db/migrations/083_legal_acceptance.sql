-- Preserve the exact legal documents and disclosure acknowledged by a person.
-- Deployment registers document snapshots only; it never accepts for anyone.
CREATE TABLE legal_policy_versions (
  kind TEXT NOT NULL CHECK (kind IN ('terms', 'privacy', 'wording')),
  version TEXT NOT NULL CHECK (CHAR_LENGTH(version) BETWEEN 1 AND 80),
  content TEXT NOT NULL CHECK (CHAR_LENGTH(content) > 0),
  content_sha256 TEXT NOT NULL CHECK (content_sha256 ~ '^[a-f0-9]{64}$'),
  registered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (kind, version)
);

CREATE TABLE user_legal_acceptances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  review_version TEXT NOT NULL CHECK (CHAR_LENGTH(review_version) BETWEEN 1 AND 80),
  terms_kind TEXT NOT NULL DEFAULT 'terms' CHECK (terms_kind = 'terms'),
  terms_version TEXT NOT NULL,
  privacy_kind TEXT NOT NULL DEFAULT 'privacy' CHECK (privacy_kind = 'privacy'),
  privacy_version TEXT NOT NULL,
  wording_kind TEXT NOT NULL DEFAULT 'wording' CHECK (wording_kind = 'wording'),
  wording_version TEXT NOT NULL,
  accepted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  source TEXT NOT NULL DEFAULT 'account_review' CHECK (source = 'account_review'),
  FOREIGN KEY (terms_kind, terms_version) REFERENCES legal_policy_versions(kind, version),
  FOREIGN KEY (privacy_kind, privacy_version) REFERENCES legal_policy_versions(kind, version),
  FOREIGN KEY (wording_kind, wording_version) REFERENCES legal_policy_versions(kind, version),
  UNIQUE (user_id, review_version)
);

CREATE FUNCTION reject_legal_policy_mutation() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Legal document versions are immutable; register a new version';
END
$$;
CREATE TRIGGER legal_policy_versions_immutable
BEFORE UPDATE OR DELETE ON legal_policy_versions
FOR EACH ROW EXECUTE FUNCTION reject_legal_policy_mutation();

CREATE FUNCTION protect_legal_acceptance_history() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  -- Account deletion may remove its receipt; normal application writes never
  -- rewrite or remove acceptance evidence. TRUNCATE remains usable in tests.
  IF TG_OP = 'DELETE' AND NOT EXISTS (SELECT 1 FROM users WHERE id = OLD.user_id) THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION 'Legal acceptance history is append-only';
END
$$;
CREATE TRIGGER user_legal_acceptances_append_only
BEFORE UPDATE OR DELETE ON user_legal_acceptances
FOR EACH ROW EXECUTE FUNCTION protect_legal_acceptance_history();

COMMENT ON TABLE user_legal_acceptances IS
  'Explicit account agreement evidence, not email/SMS consent. No historical acceptance backfill.';
