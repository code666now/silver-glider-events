CREATE TABLE homepage_photos (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title                 TEXT NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 100),
  alt_text              TEXT NOT NULL CHECK (char_length(btrim(alt_text)) BETWEEN 1 AND 180),
  credit                TEXT NOT NULL DEFAULT '' CHECK (char_length(credit) <= 120),
  image_url             TEXT NOT NULL CHECK (char_length(image_url) BETWEEN 1 AND 600),
  width                 INTEGER NOT NULL CHECK (width BETWEEN 1 AND 4000),
  height                INTEGER NOT NULL CHECK (height BETWEEN 1 AND 4000),
  cloudinary_public_id  TEXT UNIQUE CHECK (char_length(cloudinary_public_id) BETWEEN 1 AND 300),
  sort_order            INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  active                BOOLEAN NOT NULL DEFAULT TRUE,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX homepage_photos_display_idx ON homepage_photos (sort_order, id) WHERE active;
